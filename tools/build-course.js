#!/usr/bin/env node
/* Authoring only: compile docs/course.json + docs/chN/*.md into data/course.js (lessons, exams, glossary). */
'use strict';
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const spec = JSON.parse(fs.readFileSync(path.join(root, 'docs/course.json'), 'utf8'));
const fast = new Set(spec.fast);
const exams = new Map(spec.exams.map(e => [e.id, e]));
const problems = [];

// `::: term 한글 | English | 약어 | 현장말` … `:::` — the definition boxes become the glossary.
function terms(md, lesson) {
  const out = [];
  const re = /^::: term (.+)\n([\s\S]*?)\n:::\s*$/gm;
  let m;
  while ((m = re.exec(md))) {
    const [ko, en = '', abbr = '-', slang = '-'] = m[1].split('|').map(s => s.trim());
    const body = m[2].split('\n');
    const exLine = body.find(l => l.startsWith('EN:'));
    const def = body.filter(l => !l.startsWith('EN:')).join(' ').trim();
    if (!ko || !en || !def) problems.push(`${lesson}: incomplete term box "${m[1]}"`);
    out.push({ko, en, abbr: abbr === '-' ? '' : abbr, slang: slang === '-' ? '' : slang,
      def, ex: exLine ? exLine.replace(/^EN:\s*/, '').replace(/^"|"$/g, '') : '', lesson});
  }
  return out;
}

function lint(md, id) {
  const opens = (md.match(/^<details><summary>/gm) || []).length;
  const closes = (md.match(/^<\/details>\s*$/gm) || []).length;
  if (opens !== closes) problems.push(`${id}: <details> ${opens} opened vs ${closes} closed`);
  const boxes = (md.match(/^::: term /gm) || []).length;
  const ends = (md.match(/^:::\s*$/gm) || []).length;
  if (boxes !== ends) problems.push(`${id}: ::: term ${boxes} opened vs ${ends} closed`);
}

const glossary = [];
const chapters = spec.chapters.map(ch => {
  const sections = ch.items.map(id => {
    const file = path.join('docs', ch.id, `${id}.md`);
    const full = path.join(root, file);
    if (!fs.existsSync(full)) { problems.push(`missing ${file}`); return null; }
    const md = fs.readFileSync(full, 'utf8').trim() + '\n';
    const heading = /^#\s+(.+)$/m.exec(md);
    if (!heading) throw new Error(`Missing title: ${file}`);
    const title = heading[1].replace(new RegExp(`^${id}\\s*[.·—-]*\\s*`), '').trim();
    lint(md, id);
    const kind = exams.has(id) ? 'exam' : 'lesson';
    if (kind === 'lesson') glossary.push(...terms(md, id));
    return {id, title, file, md, kind, fast: fast.has(id)};
  }).filter(Boolean);
  return {id: ch.id, num: ch.num, title: ch.title, lead: ch.lead, sections};
});

const order = chapters.flatMap(ch => ch.sections.map(s => s.id));
if (new Set(order).size !== order.length) throw new Error('Duplicate section ID');

// One definition per term: a second box for the same Korean or English name is an authoring error.
const seen = new Map();
for (const t of glossary) {
  for (const key of [t.ko, t.en.toLowerCase()]) {
    if (seen.has(key)) problems.push(`duplicate term "${key}" in ${seen.get(key)} and ${t.lesson}`);
    else seen.set(key, t.lesson);
  }
}
// Where each term reappears after its defining lesson (spaced re-encounters).
const lessons = chapters.flatMap(ch => ch.sections).filter(s => s.kind === 'lesson');
for (const t of glossary) {
  const at = order.indexOf(t.lesson);
  const needles = [t.ko, t.abbr].filter(x => x && x.length > 1);
  t.also = lessons.filter(s => order.indexOf(s.id) > at && needles.some(n => s.md.includes(n))).map(s => s.id);
}

for (const e of spec.exams) {
  if (!order.includes(e.id)) problems.push(`exam ${e.id} not placed in a chapter`);
  for (const l of e.lessons) if (!order.includes(l)) problems.push(`exam ${e.id} links unknown lesson ${l}`);
}

const data = {title: spec.title, fast: spec.fast, chapters, exams: spec.exams, glossary};
fs.writeFileSync(path.join(root, 'data/course.js'),
  '// Generated by tools/build-course.js from docs/course.json and docs/chN/*.md — do not edit.\nwindow.COURSE = ' + JSON.stringify(data) + ';\n');
console.log(`Built course → ${chapters.map(c => `${c.id}:${c.sections.length}`).join(' ')} · terms ${glossary.length}`);
if (problems.length) {
  console.error('Problems:\n- ' + problems.join('\n- '));
  if (process.argv.includes('--strict')) process.exit(1);
}
